"""Checks candidate company IDs against each official API and writes the working ones to
data/sources.yaml. Run it when adding companies:  python -m classifier.discover"""

from __future__ import annotations

import asyncio
import os

import yaml

from classifier.sources import client

CANDIDATES_FILE = os.environ.get("CANDIDATES", "data/candidates.yaml")
SOURCES_FILE = os.environ.get("SOURCES_OUT", "data/sources.yaml")

PROBES = {
    "greenhouse": ("https://boards-api.greenhouse.io/v1/boards/{}/jobs", lambda d: len(d.get("jobs", []))),
    "lever": ("https://api.lever.co/v0/postings/{}?mode=json&limit=1", lambda d: len(d) if isinstance(d, list) else 0),
    "ashby": ("https://api.ashbyhq.com/posting-api/job-board/{}", lambda d: len(d.get("jobs", []))),
    "workable": ("https://apply.workable.com/api/v1/widget/accounts/{}", lambda d: len(d.get("jobs", []))),
    "smartrecruiters": ("https://api.smartrecruiters.com/v1/companies/{}/postings?limit=1", lambda d: d.get("totalFound", 0)),
}


async def main() -> None:
    with open(CANDIDATES_FILE) as f:
        candidates = yaml.safe_load(f)
    found: dict[str, list[str]] = {}
    gate = asyncio.Semaphore(10)
    async with client() as http:

        async def probe(source: str, account: str):
            url, count = PROBES[source]
            async with gate:
                try:
                    resp = await http.get(url.format(account))
                    n = count(resp.json()) if resp.status_code == 200 else 0
                except Exception:
                    n = 0
            if n:
                found.setdefault(source, []).append(account)

        await asyncio.gather(*(probe(s, a) for s, accts in candidates.items() if s in PROBES for a in accts))

    config = {s: sorted(set(found.get(s, []))) for s in PROBES}
    config["remotive"] = ["all"]
    config["usajobs"] = candidates.get("usajobs", [])
    config["adzuna"] = candidates.get("adzuna", [])
    with open(SOURCES_FILE, "w") as f:
        f.write("# Generated by `python -m classifier.discover` from data/candidates.yaml. Official public feeds only.\n")
        yaml.safe_dump(config, f, sort_keys=False)
    for s in PROBES:
        print(f"{s:16} {len(config[s]):4} working of {len(set(candidates.get(s, [])))} candidates")


if __name__ == "__main__":
    asyncio.run(main())
